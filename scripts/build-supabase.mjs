/**
 * Bundles the API (apps/server/src/supabase.ts) into one self-contained file
 * for the Supabase Edge Function: supabase/functions/api/index.ts.
 * Deploy it with the Supabase CLI (`supabase functions deploy api --no-verify-jwt`)
 * or paste it into the dashboard editor. See README → Deploy.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = resolve(root, 'supabase/functions/api/index.ts');

await build({
  entryPoints: [resolve(root, 'apps/server/src/supabase.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'none',
  minify: true,
  logLevel: 'warning',
});

const header = [
  '// @ts-nocheck',
  '// GENERATED by `npm run build:supabase` from apps/server/src/supabase.ts — do not edit by hand.',
  '// Futbolchi Pro API as a Supabase Edge Function (deploy with JWT verification OFF).',
  '',
].join('\n');
writeFileSync(outfile, header + readFileSync(outfile, 'utf8'));
console.log(`[supabase] bundled → ${outfile.replace(root + '\\', '').replace(root + '/', '')} (${Math.round(readFileSync(outfile).length / 1024)} KB)`);
